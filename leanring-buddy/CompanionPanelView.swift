    private func openRouterModelPickerRow(
        title: String,
        models: [OpenRouterModelOption],
        selectedModelID: String,
        onSelect: @escaping (String) -> Void
    ) -> some View {
        let selectedOption = models.first(where: { $0.id == selectedModelID }) ?? models[0]

        return HStack {
            Text(title)
                .font(.system(size: 13, weight: .medium))
                .foregroundColor(DS.Colors.textSecondary)

            Spacer()

            Menu {
                ForEach(models) { model in
                    Button(action: { onSelect(model.id) }) {
                        HStack {
                            Text("\(model.displayName) — \(model.subtitle)")
                            if model.id == selectedModelID {
                                Image(systemName: "checkmark")
                            }
                        }
                    }
                }
            } label: {
                HStack(spacing: 6) {
                    VStack(alignment: .trailing, spacing: 1) {
                        Text(selectedOption.displayName)
                            .font(.system(size: 11, weight: .semibold))
                            .foregroundColor(DS.Colors.textPrimary)
                        Text(selectedOption.subtitle)
                            .font(.system(size: 9))
                            .foregroundColor(DS.Colors.textTertiary)
                    }
                    Image(systemName: "chevron.up.chevron.down")
                        .font(.system(size: 9, weight: .semibold))
                        .foregroundColor(DS.Colors.textTertiary)
                }
                .padding(.horizontal, 10)
                .padding(.vertical, 5)
                .background(
                    RoundedRectangle(cornerRadius: 6, style: .continuous)
                        .fill(Color.white.opacity(0.06))
                )
                .overlay(
                    RoundedRectangle(cornerRadius: 6, style: .continuous)
                        .stroke(DS.Colors.borderSubtle, lineWidth: 0.5)
                )
            }
            .menuStyle(.borderlessButton)
            .pointerCursor()
        }
    }

    // MARK: - Agent Status

    @ViewBuilder
    private var agentStatusSection: some View {
        let agent = companionManager.backgroundAgentManager

        VStack(alignment: .leading, spacing: 8) {
            Text("AGENT STATUS")
                .font(.system(size: 10, weight: .semibold, design: .rounded))
                .foregroundColor(DS.Colors.textTertiary)

            HStack(spacing: 8) {
                Circle()
                    .fill(agentStatusColor)
                    .frame(width: 8, height: 8)

                Text(agentStatusText)
                    .font(.system(size: 12, weight: .medium))
                    .foregroundColor(DS.Colors.textSecondary)

                Spacer()

                if case .running = agent.status {
                    ProgressView()
                        .scaleEffect(0.6)
                        .frame(width: 16, height: 16)
                }
            }

            if !agent.stepLog.isEmpty {
                VStack(alignment: .leading, spacing: 4) {
                    ForEach(agent.stepLog.suffix(3)) { step in
                        HStack(alignment: .top, spacing: 6) {
                            Image(systemName: "terminal")
                                .font(.system(size: 9))
                                .foregroundColor(DS.Colors.textTertiary)
                                .frame(width: 12)

                            VStack(alignment: .leading, spacing: 1) {
                                Text(step.toolName)
                                    .font(.system(size: 11, weight: .medium))
                                    .foregroundColor(DS.Colors.textSecondary)

                                Text(step.result.prefix(80))
                                    .font(.system(size: 10))
                                    .foregroundColor(DS.Colors.textTertiary)
                                    .lineLimit(2)
                            }
                        }
                        .padding(8)
                        .background(
                            RoundedRectangle(cornerRadius: 6, style: .continuous)
                                .fill(Color.white.opacity(0.04))
                        )
                    }
                }
            }

            if case .completed(let result) = agent.status {
                HStack(alignment: .top, spacing: 6) {
                    Image(systemName: "checkmark.circle")
                        .font(.system(size: 11))
                        .foregroundColor(DS.Colors.success)

                    Text(result.prefix(200))
                        .font(.system(size: 11))
                        .foregroundColor(DS.Colors.textSecondary)
                        .lineLimit(4)
                }
                .padding(8)
                .background(
                    RoundedRectangle(cornerRadius: 6, style: .continuous)
                        .fill(DS.Colors.success.opacity(0.1))
                )
            }

            if case .failed(let error) = agent.status {
                HStack(alignment: .top, spacing: 6) {
                    Image(systemName: "exclamationmark.triangle")
                        .font(.system(size: 11))
                        .foregroundColor(DS.Colors.warning)

                    Text(error)
                        .font(.system(size: 11))
                        .foregroundColor(DS.Colors.warning)
                }
                .padding(8)
                .background(
                    RoundedRectangle(cornerRadius: 6, style: .continuous)
                        .fill(DS.Colors.warning.opacity(0.1))
                )
            }
        }
        .padding(.vertical, 8)
    }

    private var agentStatusColor: Color {
        switch companionManager.backgroundAgentManager.status {
        case .idle: return DS.Colors.textTertiary
        case .reasoning, .running: return DS.Colors.blue400
        case .completed: return DS.Colors.success
        case .failed: return DS.Colors.warning
        }
    }

    private var agentStatusText: String {
        switch companionManager.backgroundAgentManager.status {
        case .idle: return "Idle"
        case .reasoning: return "Thinking..."
        case .running(let tool): return "Running \(tool)..."
        case .completed: return "Done"
        case .failed: return "Failed"
        }
    }

